-- C1 · 身份、配额与用量账本
--
-- 【约定修订】本文件的存在本身是原「薄网关」约定的一次显式修订。
-- 原约定是"网关不依赖数据库，以免有人把业务逻辑写进来"。
-- 但**身份、配额、用量记账属于平台能力，不是业务逻辑**——
-- 业务逻辑是"证据怎么装配"，那部分始终只由 Python 编排服务负责。
-- 修订记录见 CHANGELOG。
--
-- SQL 刻意写成 **PostgreSQL 与 H2 都可执行** 的子集：
-- 默认测试档用 H2（PostgreSQL 兼容模式）跑同一套迁移，
-- 这样迁移脚本本身每次测试都被执行；真实 PostgreSQL 由 gateway-it 用
-- Testcontainers 另跑一遍。若此处用了 jsonb / uuid 等 PG 专有类型，
-- 迁移就只能在有 Docker 的机器上被验证。

CREATE TABLE quota_policy (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(64)  NOT NULL UNIQUE,
    daily_run_limit     INTEGER      NOT NULL,
    daily_token_limit   BIGINT       NOT NULL,
    monthly_token_limit BIGINT       NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE api_credential (
    id              VARCHAR(36) PRIMARY KEY,
    name            VARCHAR(80) NOT NULL,
    -- 只存 SHA-256 十六进制摘要。库被拖走后拿不到可用的 key，
    -- 也不存在"忘了删日志里的明文"这种事故面。
    key_hash        VARCHAR(64) NOT NULL UNIQUE,
    -- 只留前若干字符供人辨认（"这把是 plx_3f9a…"），不足以还原 key
    key_prefix      VARCHAR(16) NOT NULL,
    role            VARCHAR(16) NOT NULL,
    quota_policy_id BIGINT      NOT NULL REFERENCES quota_policy (id),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at      TIMESTAMP WITH TIME ZONE,
    last_used_at    TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_api_credential_hash ON api_credential (key_hash);

-- 用量账本：只追加，不回改。
-- 刻意用 credential_id 字符串而不是外键对象：账本不该持有可变实体引用，
-- 否则删改凭据会波及历史账目。
CREATE TABLE usage_ledger (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credential_id     VARCHAR(36) NOT NULL REFERENCES api_credential (id),
    run_id            VARCHAR(64) NOT NULL,
    occurred_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    prompt_tokens     BIGINT      NOT NULL,
    completion_tokens BIGINT      NOT NULL,
    total_tokens      BIGINT      NOT NULL,
    trace_id          VARCHAR(64),
    -- 同一次运行只能记一笔：完成回调可能因重试被投递多次，
    -- 没有这条约束就会重复计费。
    CONSTRAINT uq_usage_run UNIQUE (run_id)
);

CREATE INDEX idx_usage_credential_time ON usage_ledger (credential_id, occurred_at);

