-- C2 · 运行事件留痕
--
-- 记录的是**网关这个视角看得见**的生命周期事件：提交、完成、失败。
-- 编排内部的事件（分区、盲读、聚合、补检……）**刻意不在这里重复存一份**——
-- Python 编排服务已有可重放的事件总线（`parallax/service/events.py`），
-- 它的序号与断线重放语义是为 SSE 客户端设计的，网关复制一份只会造出
-- 两份可能不一致的事实来源。运行详情里直接给出上游的事件流地址。
--
-- run_id 用字符串而不加外键到 audit_run：事件应该能在提交记录被清理后仍然可读，
-- 而且上游补建的运行记录可能在事件写入之后才出现。

CREATE TABLE audit_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id     VARCHAR(64) NOT NULL,
    event_type VARCHAR(48) NOT NULL,
    at         TIMESTAMP WITH TIME ZONE NOT NULL,
    detail     VARCHAR(1024),
    trace_id   VARCHAR(64)
);

CREATE INDEX idx_audit_event_run ON audit_event (run_id, at);
